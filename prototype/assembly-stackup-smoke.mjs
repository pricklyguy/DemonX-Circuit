import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {evaluateAssembly}=createRequire(import.meta.url)('../desktop/dist/assembly-stackup.js');
// Synthetic dimensions; this fixture is not an owner's appliance or selected component.
const input={format:'demonx-assembly-stackup-v1',datumLabel:'Synthetic datum',displayRearMm:2.5,malePinExtensionMm:7,femaleBodyMm:6,existingPcbFrontMm:8,proposedPcbFrontMm:11,pcbThicknessMm:1.5,actuatorTipMm:2,switchHeightMm:4,targetRestGapMm:.25,targetPlasticClearanceMm:.5,alternativesMm:[8,10,11]};
const result=evaluateAssembly(input,1.5);
assert.equal(result.existing.displayBoardClearanceMm,-.5);
assert.match(result.existing.contactStatus,/FAIL exterior/);
assert.equal(result.proposed.insertionMm,4.5);
assert.match(result.proposed.contactStatus,/UNVERIFIED/,'body height alone must never claim contact fit');
assert.equal(result.proposed.proposedActuatorMm,6.75);
assert.equal(result.makeStrokeMm,null);
assert.equal(result.proposed.rearSocketMouthMm,null);
const withContacts={...input,socketCavityDepthMm:5,contactStartMm:1,contactEndMm:4,requiredContactOverlapMm:2,switchOperatingTravelMm:.2,switchSafeTravelMm:.4,rearSocketBodyMm:5,malePlasticProjectionMm:1};
const entered=evaluateAssembly(withContacts);
assert.equal(entered.proposed.contactOverlapMm,3);
assert.equal(entered.makeStrokeMm,.45);assert.equal(entered.maximumStopStrokeMm,.65);
assert.match(entered.proposed.contactStatus,/Nominal entered/);
const ownerTarget=evaluateAssembly({...input,proposedPcbFrontMm:12.89,proposedPcbFrontStatus:'owner-selected-target',proposedPcbFrontBasis:'Synthetic physically seated connector reference'},1.6);
assert.equal(ownerTarget.proposed.pcbRearMm,14.49);
assert.equal(ownerTarget.proposedPcbFrontStatus,'owner-selected-target');
assert.match(ownerTarget.proposedPcbFrontBasis,/physically seated/);
const seated=evaluateAssembly({...input,displayRearMm:2,malePinExtensionMm:8,proposedPcbFrontMm:12.89,femaleBodyMm:10.89,targetPlasticClearanceMm:0,matingFullySeatedObserved:true},1.6);
assert.equal(seated.proposed.socketMouthMm,2);
assert.equal(seated.proposed.displayBoardClearanceMm,0);
assert.equal(seated.proposed.insertionMm,8);
assert.equal(seated.proposed.pcbRearMm,14.49);
assert.match(seated.proposed.contactStatus,/full-seat observed.*solder-tail clearance.*UNVERIFIED/);
assert.ok(seated.warnings.some(s=>s.includes('supports the nominal reference only')));
assert.match(evaluateAssembly({...withContacts,socketCavityDepthMm:4.2}).proposed.contactStatus,/FAIL/);
assert.ok(evaluateAssembly({...input,malePlasticProjectionMm:3}).proposed.warnings.some(s=>s.includes('male-header plastic')));
assert.equal(evaluateAssembly(input,2).proposed.pcbRearMm,13);
assert.ok(evaluateAssembly(input,2).warnings.some(s=>s.includes('thickness differs')));
assert.throws(()=>evaluateAssembly({...input,proposedPcbFrontMm:NaN}),/Invalid assembly/);
assert.throws(()=>evaluateAssembly({...withContacts,contactEndMm:.5}),/increasing depths/);
assert.throws(()=>evaluateAssembly({...withContacts,switchSafeTravelMm:.1}),/smaller than operating/);
assert.throws(()=>evaluateAssembly({...input,datumLabel:''}),/reference plane/);
console.log('PASS: exterior interference, unknown-contact refusal, bounded contact overlap, actuator/stop arithmetic, native thickness authority and invalid dimensional input refusal.');
