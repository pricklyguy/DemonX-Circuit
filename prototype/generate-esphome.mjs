#!/usr/bin/env node
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { constants } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const stdoutOnly = args.includes('--stdout');
const projectArg = args.indexOf('--project');
if (projectArg >= 0 && (!args[projectArg + 1] || args[projectArg + 1].startsWith('--'))) throw new Error('--project requires a project.json path');
const projectPath = projectArg >= 0 ? resolve(args[projectArg + 1]) : resolve(repo, 'examples/esp32-sensor/project.json');
const project = JSON.parse(await readFile(projectPath, 'utf8'));
const secretsTemplate = resolve(repo, 'examples/esp32-sensor/esphome-secrets.example.yaml');
const controller = project.hardware.controller;
const pinMap = project.hardware.pinMap;
const force = args.includes('--force');
const verifiedArg = args.indexOf('--verified-netlist');
const verifiedPath = verifiedArg >= 0 ? args[verifiedArg + 1] : undefined;
if (verifiedArg >= 0 && (!verifiedPath || verifiedPath.startsWith('--'))) throw new Error('--verified-netlist requires a JSON file exported after native KiCad netlist verification');
const outputArgs = args.filter((arg, index) => arg !== '--force' && arg !== '--stdout' && index !== verifiedArg && !(verifiedArg >= 0 && index === verifiedArg + 1) && index !== projectArg && !(projectArg >= 0 && index === projectArg + 1));
if (outputArgs.length > 1 || (stdoutOnly && outputArgs.length)) throw new Error('Usage: node generate-esphome.mjs [output.yaml] [--project project.json] [--verified-netlist verified-netlist.json] [--stdout] [--force]');
const output = outputArgs[0] ? resolve(outputArgs[0]) : resolve(repo, 'examples/esp32-sensor/esphome.yaml');
if (!stdoutOnly) await mkdir(dirname(output), { recursive: true });
if (controller.esphomeVariant !== 'esp32s3') throw new Error(`Unsupported ESPHome variant ${controller.esphomeVariant}`);
const map = Object.fromEntries(project.hardware.nets.flatMap(net => net.connections.map(endpoint => [endpoint, net.name])));
const pins = { sda: pinMap.I2C_SDA, scl: pinMap.I2C_SCL, relay: pinMap.RELAY_DRIVER };
const native = verifiedPath ? JSON.parse(await readFile(resolve(verifiedPath), 'utf8')) : undefined;
const nativeMap = native?.netByPin;
const nativePinNumbers = controller.nativePinNumbers ?? {};
for (const [signal, gpio] of Object.entries(pins)) {
  if (!/^GPIO\d+$/.test(gpio ?? '')) throw new Error(`Invalid or missing GPIO for ${signal}: ${gpio}`);
  const pinNumber = nativePinNumbers[gpio];
  const expectedNet = { sda: 'I2C_SDA', scl: 'I2C_SCL', relay: 'RELAY_GPIO' }[signal];
  if (!pinNumber) throw new Error(`No datasheet-derived native pin number is recorded for ${gpio}`);
  if (!map[`U1.${gpio}`]) throw new Error(`Required GPIO is not explicitly connected in project metadata: U1.${gpio}`);
  if (verifiedPath && nativeMap[`U1.${pinNumber}`] !== expectedNet) {
    throw new Error(`Native KiCad netlist does not verify ${gpio} on U1 pin ${pinNumber} as ${expectedNet}`);
  }
}
await readFile(secretsTemplate, 'utf8');

const yaml = `# Generated by the DemonX Circuit feasibility prototype. Review before flashing.
# Circuit connectivity does not determine sensor behavior, relay polarity, or credentials.
substitutions:
  device_name: dx-esp32-sensor
  friendly_name: DemonX ESP32 Sensor
  esp32_variant: ${controller.esphomeVariant}
  i2c_sda: ${pins.sda}
  i2c_scl: ${pins.scl}
  relay_gpio: ${pins.relay}

esphome:
  name: \${device_name}
  friendly_name: \${friendly_name}

esp32:
  variant: \${esp32_variant}
  framework:
    type: arduino

logger:

api:
  encryption:
    key: !secret api_encryption_key

ota:
  - platform: esphome
    password: !secret ota_password

wifi:
  ssid: !secret wifi_ssid
  password: !secret wifi_password
  ap:
    ssid: \${friendly_name} Fallback
    password: !secret fallback_ap_password

captive_portal:

i2c:
  sda: \${i2c_sda}
  scl: \${i2c_scl}
  scan: true

sensor:
  - platform: bme280_i2c
    address: 0x76
    temperature:
      name: "\${friendly_name} Temperature"
    pressure:
      name: "\${friendly_name} Pressure"
    humidity:
      name: "\${friendly_name} Humidity"
    update_interval: 60s

# GPIO10 is an explicit logical pin mapping. This is not electrically verified.
# Confirm the final driver circuit, safe boot state, and relay polarity before use.
switch:
  - platform: gpio
    name: "\${friendly_name} Relay"
    pin: \${relay_gpio}
    restore_mode: ALWAYS_OFF
`;

if (stdoutOnly) {
  process.stdout.write(yaml);
  process.stderr.write(verifiedPath ? `Native KiCad connectivity source: ${native.source}\n` : 'Connectivity source: project manifest only; native KiCad connectivity is not verified.\n');
  process.stderr.write('Circuit connectivity does not determine sensor behavior, relay polarity, or credentials. Review and validate before use.\n');
  process.exit(0);
}

let existing;
try { existing = await readFile(output, 'utf8'); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
if (existing !== undefined) {
  if (!force) throw new Error(`Refusing to overwrite ${output}; pass --force to back up, compare, and approve replacement.`);
  const backup = `${output}.bak`;
  await copyFile(output, backup, constants.COPYFILE_EXCL);
  console.log(`Backup created: ${backup}`);
  console.log('--- EXISTING YAML ---');
  console.log(existing);
  console.log('--- PROPOSED YAML ---');
  console.log(yaml);
  const terminal = createInterface({ input: process.stdin, output: process.stdout });
  const approval = await terminal.question('Type REPLACE to approve replacing the existing YAML: ');
  terminal.close();
  if (approval !== 'REPLACE') throw new Error(`Replacement declined; original file is unchanged. Backup: ${backup}`);
}
await writeFile(output, yaml, { flag: existing === undefined ? 'wx' : 'w' });
console.log(`Generated ${output}`);
console.log(`ESPHome target: ESP32-S3 (${controller.esphomeVariant}); ${pins.sda} SDA, ${pins.scl} SCL, ${pins.relay} relay driver.`);
console.log(verifiedPath ? `Native KiCad connectivity source: ${native.source}` : 'Connectivity source: project manifest only; native KiCad connectivity is not verified.');
console.log('This does not validate circuit suitability or behavior. Credentials are placeholders. Validate with the installed ESPHome CLI before use.');
