#!/usr/bin/env node
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { constants } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const project = JSON.parse(await readFile(resolve(repo, 'examples/esp32-sensor/project.json'), 'utf8'));
const secretsTemplate = resolve(repo, 'examples/esp32-sensor/esphome-secrets.example.yaml');
const controller = project.hardware.controller;
const pinMap = project.hardware.pinMap;
const args = process.argv.slice(2);
const force = args.includes('--force');
const outputArgs = args.filter(arg => arg !== '--force');
if (outputArgs.length > 1) throw new Error('Usage: node generate-esphome.mjs [output.yaml] [--force]');
const output = outputArgs[0] ? resolve(outputArgs[0]) : resolve(repo, 'examples/esp32-sensor/esphome.yaml');
await mkdir(dirname(output), { recursive: true });
if (controller.esphomeVariant !== 'esp32s3') throw new Error(`Unsupported ESPHome variant ${controller.esphomeVariant}`);
const map = Object.fromEntries(project.hardware.nets.flatMap(net => net.connections.map(endpoint => [endpoint, net.name])));
const pins = { sda: pinMap.I2C_SDA, scl: pinMap.I2C_SCL, relay: pinMap.RELAY_DRIVER };
for (const [signal, gpio] of Object.entries(pins)) {
  if (!/^GPIO\d+$/.test(gpio ?? '')) throw new Error(`Invalid or missing GPIO for ${signal}: ${gpio}`);
  if (!map[`U1.${gpio}`]) throw new Error(`Required pin is not explicitly connected: U1.${gpio}`);
}
await readFile(secretsTemplate, 'utf8');

const yaml = `# Generated by the DemonX Circuit feasibility prototype. Review before flashing.
# Circuit connectivity does not determine sensor behavior, relay polarity, or credentials.
substitutions:
  device_name: dx-esp32-sensor
  friendly_name: DemonX ESP32 Sensor
  esp32_variant: ${controller.esphomeVariant}
  i2c_sda: ${pins.sda}
  i2c_scl: ${pins.scl}
  relay_gpio: ${pins.relay}

esphome:
  name: \${device_name}
  friendly_name: \${friendly_name}

esp32:
  variant: \${esp32_variant}
  framework:
    type: arduino

logger:

api:
  encryption:
    key: !secret api_encryption_key

ota:
  - platform: esphome
    password: !secret ota_password

wifi:
  ssid: !secret wifi_ssid
  password: !secret wifi_password
  ap:
    ssid: \${friendly_name} Fallback
    password: !secret fallback_ap_password

captive_portal:

i2c:
  sda: \${i2c_sda}
  scl: \${i2c_scl}
  scan: true

sensor:
  - platform: bme280_i2c
    address: 0x76
    temperature:
      name: "\${friendly_name} Temperature"
    pressure:
      name: "\${friendly_name} Pressure"
    humidity:
      name: "\${friendly_name} Humidity"
    update_interval: 60s

# GPIO10 is an explicit logical pin mapping. This is not electrically verified.
# Confirm the final driver circuit, safe boot state, and relay polarity before use.
switch:
  - platform: gpio
    name: "\${friendly_name} Relay"
    pin: \${relay_gpio}
    restore_mode: ALWAYS_OFF
`;

let existing;
try { existing = await readFile(output, 'utf8'); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
if (existing !== undefined) {
  if (!force) throw new Error(`Refusing to overwrite ${output}; pass --force to back up, compare, and approve replacement.`);
  const backup = `${output}.bak`;
  await copyFile(output, backup, constants.COPYFILE_EXCL);
  console.log(`Backup created: ${backup}`);
  console.log('--- EXISTING YAML ---');
  console.log(existing);
  console.log('--- PROPOSED YAML ---');
  console.log(yaml);
  const terminal = createInterface({ input: process.stdin, output: process.stdout });
  const approval = await terminal.question('Type REPLACE to approve replacing the existing YAML: ');
  terminal.close();
  if (approval !== 'REPLACE') throw new Error(`Replacement declined; original file is unchanged. Backup: ${backup}`);
}
await writeFile(output, yaml, { flag: existing === undefined ? 'wx' : 'w' });
console.log(`Generated ${output}`);
console.log(`ESPHome target: ESP32-S3 (${controller.esphomeVariant}); ${pins.sda} SDA, ${pins.scl} SCL, ${pins.relay} relay driver.`);
console.log('This logical pin map is not an ERC/DRC-verified circuit. Credentials are placeholders. Validate with the installed ESPHome CLI before use.');
